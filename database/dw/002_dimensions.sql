CREATE TABLE dw.dim_customer_profile (
    customer_profile_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (customer_profile_key >= 0),
    customer_type_code text NOT NULL CHECK (customer_type_code = upper(btrim(customer_type_code)) AND customer_type_code <> ''),
    customer_type_name text NOT NULL CHECK (btrim(customer_type_name) <> ''),
    repeat_status text NOT NULL CHECK (repeat_status IN ('NEW', 'REPEAT', 'UNKNOWN')),
    is_repeated_guest boolean,
    is_unknown boolean NOT NULL,
    UNIQUE (customer_type_code, repeat_status),
    CONSTRAINT ck_profile_unknown CHECK (
        (customer_profile_key = 0) = (customer_type_code = 'UNKNOWN' AND repeat_status = 'UNKNOWN')
        AND is_unknown = (customer_profile_key = 0)
        AND (customer_type_code <> 'UNKNOWN' OR customer_type_name = 'Unknown')
    ),
    CONSTRAINT ck_profile_repeat CHECK (
        is_repeated_guest IS NOT DISTINCT FROM
            CASE repeat_status WHEN 'NEW' THEN false WHEN 'REPEAT' THEN true ELSE NULL::boolean END
    )
);
INSERT INTO dw.dim_customer_profile(customer_profile_key, customer_type_code, customer_type_name,
                                    repeat_status, is_repeated_guest, is_unknown)
    VALUES (0, 'UNKNOWN', 'Unknown', 'UNKNOWN', NULL, true);

