CREATE TABLE dw.dim_date (
    date_key integer PRIMARY KEY CHECK (date_key > 0),
    full_date date NOT NULL UNIQUE CHECK (isfinite(full_date)),
    year smallint NOT NULL,
    quarter smallint NOT NULL,
    month smallint NOT NULL,
    day_of_month smallint NOT NULL,
    iso_year smallint NOT NULL,
    iso_week smallint NOT NULL,
    day_of_week smallint NOT NULL,
    day_name text NOT NULL,
    month_name text NOT NULL,
    is_weekend boolean NOT NULL,
    CONSTRAINT ck_date_attributes CHECK (
        year = extract(year FROM full_date) AND quarter = extract(quarter FROM full_date)
        AND month = extract(month FROM full_date) AND day_of_month = extract(day FROM full_date)
        AND iso_year = extract(isoyear FROM full_date) AND iso_week = extract(week FROM full_date)
        AND day_of_week = extract(isodow FROM full_date)
        AND date_key = year::integer * 10000 + month::integer * 100 + day_of_month
        AND is_weekend = (day_of_week IN (6, 7))
    ),
    CONSTRAINT ck_date_labels CHECK (
        day_name = (ARRAY['Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday'])[day_of_week]
        AND month_name = (ARRAY['January','February','March','April','May','June',
                                 'July','August','September','October','November','December'])[month]
    )
);

CREATE TABLE dw.dim_country (
    country_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (country_key >= 0),
    country_code text NOT NULL UNIQUE CHECK (country_code = upper(btrim(country_code)) AND country_code <> ''),
    country_name text NOT NULL CHECK (btrim(country_name) <> ''),
    is_unknown boolean NOT NULL,
    CONSTRAINT ck_country_unknown CHECK (
        (country_key = 0 AND country_code = 'UNK' AND country_name = 'Unknown' AND is_unknown)
        OR (country_key > 0 AND country_code <> 'UNK' AND NOT is_unknown)
    )
);
