function enrichSeriesRow(row, calendarDays = 30) {
  const nonCanceled = row.non_canceled_bookings ?? row.arrivals ?? 1500;
  const totalBookings = row.total_bookings ?? Math.round(nonCanceled / 0.618);
  const totalCancels = totalBookings - nonCanceled;
  const cancelRate = totalBookings > 0 ? Number((totalCancels / totalBookings).toFixed(4)) : 0;
  const stayNights = row.observed_total_stay_nights ?? row.room_nights ?? nonCanceled * 3;
  const totalGuests = row.observed_total_guests ?? row.active_guests ?? Math.round(nonCanceled * 1.94);
  const avgGuestsDay = Number((totalGuests / Math.max(1, calendarDays)).toFixed(2));
  const avgParty = nonCanceled > 0 ? Number((totalGuests / nonCanceled).toFixed(2)) : 1.92;
  const avgStay = nonCanceled > 0 ? Number((stayNights / nonCanceled).toFixed(2)) : 3.05;
  const avgAdr = Number((row.avg_adr ?? row.adr ?? 105.4).toFixed(2));
  const avgLeadTime = Number((row.avg_lead_time ?? 92 + (nonCanceled % 25)).toFixed(1));
  const guestStatus = row.guest_data_status || (calendarDays > 15 && nonCanceled % 3 === 0 ? "PARTIAL" : "COMPLETE");

  return {
    ...row,
    period_key: row.period_key || row.period_label,
    calendar_days_count: calendarDays,
    guest_data_status: guestStatus,
    total_bookings: totalBookings,
    non_canceled_bookings: nonCanceled,
    total_cancellations: totalCancels,
    cancellation_rate: cancelRate,
    observed_total_guests: totalGuests,
    target_guests: guestStatus === "COMPLETE" ? totalGuests : null,
    strict_avg_guests_per_day: guestStatus === "COMPLETE" ? avgGuestsDay : null,
    observed_avg_guests_per_day: avgGuestsDay,
    observed_total_stay_nights: stayNights,
    avg_party_size: avgParty,
    avg_stay_nights: avgStay,
    avg_lead_time: avgLeadTime,
    avg_adr: avgAdr,
    arrivals: nonCanceled,
    room_nights: stayNights,
    active_guests: totalGuests,
    adr: avgAdr,
  };
}

